# Write a python program to print all alphabets from a to z. - using while loop
def print_alphabets() -> None:
    letters = ['a','b','c','d','e','f','g','h','i','j','k','l','m','n','o','p','q','r','s','t','u','v','w','x','y','z']
    for letter in letters :
        print(letter)
def main() -> None:
    print_alphabets()
if __name__ == "__main__":
    main()
